function t(lang, key) {
    var d = texts[lang] || texts["en"];
    return d[key] !== undefined ? d[key] : texts["en"][key];
}

function a(lang, key, arg) {
    return t(lang, key).replace("%1", arg);
}

// lower case without diacritics, for searching
function fold(s) {
    var from = "ąćęłńóśźżäöüéèáàíúçñ", to = "acelnoszzaoueeaaiucn";
    s = s.toLowerCase();
    var out = "";
    for (var i = 0; i < s.length; ++i) {
        var k = from.indexOf(s.charAt(i));
        out += k >= 0 ? to.charAt(k) : s.charAt(i);
    }
    return out;
}
